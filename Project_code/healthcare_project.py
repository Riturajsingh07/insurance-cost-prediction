import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
from sklearn.model_selection import train_test_split
from sklearn.compose import ColumnTransformer
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import OneHotEncoder, StandardScaler
from sklearn.impute import SimpleImputer
from sklearn.linear_model import LinearRegression
from sklearn.dummy import DummyRegressor
from sklearn.metrics import mean_absolute_error,mean_squared_error,r2_score


df = pd.read_csv("/content/insurance_cost_course_data.csv")

print(df.head())
print(df.shape)
print(df.dtypes)

print(df["charges"].describe())
df["charges"].hist(bins=12)
plt.xlabel("Insurance charge")
plt.ylabel("Number of records")
plt.title("Distribution of insurance charges")
plt.show()

X = df.drop(columns=["record_id", "charges"])
y = df["charges"]
numeric_features = ["age", "bmi", "children"]
categorical_features = ["sex", "smoker", "region"]

X_train, X_test, y_train, y_test = train_test_split(
   X,
   y,
   test_size=0.20,
   random_state=42
)
print("Training rows:", len(X_train))
print("Test rows:", len(X_test))

numeric_steps = Pipeline([
   ("fill_missing", SimpleImputer(strategy="median")),
   ("scale", StandardScaler())
])
categorical_steps = Pipeline([
   ("fill_missing", SimpleImputer(strategy="most_frequent")),
   ("one_hot", OneHotEncoder(handle_unknown="ignore"))
])
preprocess = ColumnTransformer([
   ("numbers", numeric_steps, numeric_features),
   ("categories", categorical_steps, categorical_features)
])

baseline = Pipeline([
   ("preprocess", preprocess),
   ("model", DummyRegressor(strategy="mean"))
])
baseline.fit(X_train, y_train)
baseline_predictions = baseline.predict(X_test)
baseline_mae = mean_absolute_error(y_test, baseline_predictions)
print("Baseline MAE:", round(baseline_mae, 2))

model = Pipeline([
   ("preprocess", preprocess),
   ("model", LinearRegression())
])
model.fit(X_train, y_train)
predictions = model.predict(X_test)

mae = mean_absolute_error(y_test, predictions)
rmse = np.sqrt(mean_squared_error(y_test, predictions))
r2 = r2_score(y_test, predictions)
print("Linear regression MAE:", round(mae, 2))
print("Linear regression RMSE:", round(rmse, 2))
print("Linear regression R-squared:", round(r2, 3))
print("Improvement over baseline MAE:", round(baseline_mae - mae, 2))

results = X_test.copy()
results["actual"] = y_test
results["predicted"] = predictions
results["residual"] = results["actual"] - results["predicted"]
results["absolute_error"] = results["residual"].abs()
print(results.sort_values("absolute_error", ascending=False))

plt.scatter(y_test, predictions)
minimum = min(y_test.min(), predictions.min())
maximum = max(y_test.max(), predictions.max())
plt.plot([minimum, maximum], [minimum, maximum], linestyle="--")
plt.xlabel("Actual charge")
plt.ylabel("Predicted charge")
plt.title("Actual versus predicted insurance charge")
plt.show()

residuals = y_test - predictions
plt.scatter(predictions, residuals)
plt.axhline(0, linestyle="--")
plt.xlabel("Predicted charge")
plt.ylabel("Residual: actual minus predicted")
plt.title("Residuals")
plt.show()

new_person = pd.DataFrame([{
   "age": 42,
   "sex": "male",
   "bmi": 20.0,
   "children": 4,
   "smoker": "no",
   "region": "Central_west"
}])
new_prediction = model.predict(new_person)[0]
print("Estimated charge:", round(new_prediction, 2))



